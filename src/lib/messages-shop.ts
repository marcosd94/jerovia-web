export type ShopKey = keyof typeof es
const all: Record<Locale, typeof es> = { es, en, pt }

export const ts = (locale: Locale, key: ShopKey, vars?: Record<string, string | number>): string => {
  let out = all[locale]?.[key] ?? es[key]
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v))
  return out
}

/** Todos los textos de un idioma, para pasarlos a componentes de cliente */
export const shopMessages = (locale: Locale): Record<ShopKey, string> => ({ ...es, ...(all[locale] ?? {}) })
